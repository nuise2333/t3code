#!/usr/bin/env node
// Mirror the DeepSeek Stack preset into the DeepSeek Harness desktop profile so
// the desktop app offers the same mode as T3 Code. Safe to rerun.
// usage: node scripts/dsh-stack/sync-desktop.mjs
import * as NodeCrypto from "node:crypto";
import * as NodeFS from "node:fs";
import * as NodeOS from "node:os";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

const PACKAGE = "@local/dsh-deepseek-stack-preset";
const stackRoot = NodePath.dirname(NodeURL.fileURLToPath(import.meta.url));
const dshHome = process.env.DSH_HOME ?? NodePath.join(NodeOS.homedir(), ".dsh");
const profile = NodePath.join(dshHome, "profiles", "desktop");
const manifestPath = NodePath.join(profile, "package.json");
if (!NodeFS.existsSync(manifestPath))
  throw new Error(
    `No DeepSeek Harness desktop profile at ${profile}. Open the desktop app once first.`,
  );
const manifest = JSON.parse(NodeFS.readFileSync(manifestPath, "utf8"));

const specifier = manifest.dependencies?.[PACKAGE];
const bundle = specifier?.startsWith("link:")
  ? specifier.slice("link:".length)
  : NodePath.join(dshHome, "bundles", "deepseek-stack-preset");

const existing = NodePath.join(bundle, "package.json");
if (
  NodeFS.existsSync(bundle) &&
  (!NodeFS.existsSync(existing) ||
    JSON.parse(NodeFS.readFileSync(existing, "utf8")).name !== PACKAGE)
)
  throw new Error(`${bundle} exists and is not the ${PACKAGE} bundle; refusing to overwrite it.`);

const hashTree = (root) => {
  const hash = NodeCrypto.createHash("sha256");
  const walk = (dir) => {
    for (const entry of NodeFS.readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
      a.name.localeCompare(b.name),
    )) {
      const full = NodePath.join(dir, entry.name);
      hash.update(NodePath.relative(root, full));
      if (entry.isDirectory()) walk(full);
      else hash.update(NodeFS.readFileSync(full));
    }
  };
  if (NodeFS.existsSync(root)) walk(root);
  return hash.digest("hex");
};
const before = hashTree(bundle);

// The desktop roster already lists Standard, PTC, Minimal, Creator (1-4); T3 shows this one first.
const source = NodeFS.readFileSync(NodePath.join(stackRoot, "preset.patch.yml"), "utf8");
const body = source.slice(source.indexOf("- insert:"));
if (!body.includes("        order: 0\n") || !body.includes("__T3_DSH_SKILLS_DIR__"))
  throw new Error("preset.patch.yml changed shape; update sync-desktop.mjs.");
const patch =
  "# Generated by t3-code scripts/dsh-stack/sync-desktop.mjs. Edit preset.patch.yml\n" +
  "# there and rerun the script; changes made here are overwritten.\n" +
  body
    .replace("        order: 0\n", "        order: 6\n")
    .replaceAll("__T3_DSH_SKILLS_DIR__", JSON.stringify(NodePath.join(bundle, "skills")));

NodeFS.mkdirSync(bundle, { recursive: true });
NodeFS.rmSync(NodePath.join(bundle, "skills"), { recursive: true, force: true });
NodeFS.cpSync(NodePath.join(stackRoot, "skills"), NodePath.join(bundle, "skills"), {
  recursive: true,
});
NodeFS.copyFileSync(NodePath.join(stackRoot, "LICENSE"), NodePath.join(bundle, "LICENSE"));
NodeFS.writeFileSync(NodePath.join(bundle, "cordis.patch.yml"), patch);
NodeFS.writeFileSync(
  existing,
  JSON.stringify(
    {
      name: PACKAGE,
      version: "0.1.0",
      private: true,
      description:
        "DeepSeek Stack: ds-mode working style plus deepseek-stack skills routed by task.",
      type: "module",
      license: "MIT",
      dsh: { bundle: { patch: "./cordis.patch.yml" } },
    },
    null,
    2,
  ) + "\n",
);

// The desktop app owns this profile and rejects `dsh plugin`, so register the
// link the way pnpm would: manifest, lockfile importer, and node_modules link.
let registered = false;
if (specifier === undefined) {
  manifest.dependencies = Object.fromEntries(
    Object.entries({ ...manifest.dependencies, [PACKAGE]: `link:${bundle}` }).sort(([a], [b]) =>
      a.localeCompare(b),
    ),
  );
  registered = true;
}
const bundles = manifest.dsh?.profile?.bundles;
if (!Array.isArray(bundles)) throw new Error(`${manifestPath} has no dsh.profile.bundles list.`);
if (!bundles.includes(PACKAGE)) {
  bundles.push(PACKAGE);
  registered = true;
}
if (registered) NodeFS.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

const lockPath = NodePath.join(profile, "pnpm-lock.yaml");
if (NodeFS.existsSync(lockPath)) {
  const lock = NodeFS.readFileSync(lockPath, "utf8");
  const anchor = "  .:\n    dependencies:\n";
  if (!lock.includes(`      '${PACKAGE}':\n`) && lock.includes(anchor)) {
    const entry =
      `      '${PACKAGE}':\n` +
      `        specifier: link:${bundle}\n` +
      `        version: link:${NodePath.relative(profile, bundle)}\n`;
    NodeFS.writeFileSync(lockPath, lock.replace(anchor, anchor + entry));
    registered = true;
  }
}

const link = NodePath.join(profile, "node_modules", PACKAGE);
const linkTarget = NodePath.relative(NodePath.dirname(link), bundle);
let current;
try {
  current = NodeFS.readlinkSync(link);
} catch {}
if (current !== linkTarget) {
  NodeFS.mkdirSync(NodePath.dirname(link), { recursive: true });
  NodeFS.rmSync(link, { force: true });
  NodeFS.symlinkSync(linkTarget, link);
  registered = true;
}

if (!registered && hashTree(bundle) === before) {
  console.log(`DeepSeek Stack is already in sync at ${bundle}.`);
} else {
  console.log(
    `Synced DeepSeek Stack to ${bundle}${registered ? " and registered it in the desktop profile" : ""}.`,
  );
  console.log("Restart DeepSeek Harness to load it.");
}
